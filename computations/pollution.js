var POLLUTION_EQUIVALENTS = {
  carsPerLbCO2: 1 / 10141,
  gallonsGasPerLbCO2: 1 / 19.37,
  tankerTrucksPerGal: 1 / 8500,
  barrelsOilPerLbCO2: 1 / 934.4,
  householdsPerLbCO2: 1 / 16816,
  treeSeedlingsPerLbCO2: 1 / 60,
  acresForestPerLbCO2: 1 / 34700,
  railcarsCoalPerLbCO2: 1 / 446968,
  tonsRecycledPerLbCO2: 1 / 6500,
  propaneCylindersPerLbCO2: 1 / 23.6,
  coalPlantsPerLbCO2: 1 / 7900000000,
};

// Metric ton equivalents — used by PDF export
var POLLUTION_EQUIV_MT = {
  co2PerKwh: 0.000404,
  co2PerTherm: 0.005302,
  co2PerPropGal: 0.00574,
  treesPerTon: 16.5,
  carsPerTon: 1 / 4.6,
  homesPerTon: 1 / 8.9,
  acresForestPerTon: 1 / 0.84,
};

function calculatePollutionCredits(kwhSaved, thermsSaved, propaneGalSaved, stateCode, unit) {
  unit = unit || 'lbs';

  if (unit === 'mt') {
    var eq = POLLUTION_EQUIV_MT;
    var totalCO2 = kwhSaved * eq.co2PerKwh + thermsSaved * eq.co2PerTherm + propaneGalSaved * eq.co2PerPropGal;
    var lbsCO2 = totalCO2 * 2204.6;
    return {
      totalCO2: totalCO2,
      lbsCO2: lbsCO2,
      equivalents: {
        treeSeedlings: Math.round(Math.abs(totalCO2) * eq.treesPerTon),
        carsRemoved: Math.abs(totalCO2 * eq.carsPerTon),
        households: Math.abs(totalCO2 * eq.homesPerTon),
        acresForest: Math.abs(totalCO2 * eq.acresForestPerTon),
      },
      stateCode: stateCode,
      inputs: { kwhSaved: kwhSaved, thermsSaved: thermsSaved, propaneGalSaved: propaneGalSaved },
    };
  }

  // Default: lbs mode
  var state = EGRID_FACTORS[stateCode] || EGRID_FACTORS['KS'];
  var mwhSaved = kwhSaved / 1000;
  var pollutants = {};
  var keys = ['co2', 'ch4', 'n2o', 'so2', 'nox', 'hg_oz', 'pm10_oz', 'pm_filt_oz', 'voc_oz', 'co_oz'];
  keys.forEach(function (k) {
    pollutants[k] = mwhSaved * state.electric[k] + thermsSaved * state.gas[k] + propaneGalSaved * state.propane[k];
  });
  var co2Lbs = pollutants.co2;
  var eq = POLLUTION_EQUIVALENTS;
  var absCo2Lbs = Math.abs(co2Lbs);
  var equivalents = {
    carsRemoved: Math.round(absCo2Lbs * eq.carsPerLbCO2),
    gallonsGasoline: Math.round(absCo2Lbs * eq.gallonsGasPerLbCO2),
    tankerTrucks: Math.round(absCo2Lbs * eq.gallonsGasPerLbCO2 * eq.tankerTrucksPerGal),
    barrelsOil: Math.round(absCo2Lbs * eq.barrelsOilPerLbCO2),
    households: Math.round(absCo2Lbs * eq.householdsPerLbCO2),
    treeSeedlings: Math.round(absCo2Lbs * eq.treeSeedlingsPerLbCO2),
    acresForest: Math.round(absCo2Lbs * eq.acresForestPerLbCO2),
    railcarsCoal: Math.round(absCo2Lbs * eq.railcarsCoalPerLbCO2),
    tonsRecycled: Math.round(absCo2Lbs * eq.tonsRecycledPerLbCO2),
    propaneCylinders: Math.round(absCo2Lbs * eq.propaneCylindersPerLbCO2),
    coalPlants: Math.round(absCo2Lbs * eq.coalPlantsPerLbCO2),
  };
  return {
    pollutants: pollutants,
    equivalents: equivalents,
    stateCode: stateCode,
    inputs: { kwhSaved: kwhSaved, thermsSaved: thermsSaved, propaneGalSaved: propaneGalSaved },
  };
}
